import fs from 'node:fs/promises';
import path from 'node:path';
import type { Ctx } from '../context.js';
import { sessionDir } from './sessions.js';

// Filesystem exports are derived, read-only representations of database state.
// They are rewritten atomically (write temp file, then rename) and never read back as truth.

async function writeAtomic(file: string, content: string) {
  await fs.mkdir(path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
  await fs.writeFile(tmp, content, 'utf8');
  await fs.rename(tmp, file);
}

interface MemoryExportRow {
  id: string;
  title: string;
  content: string;
  tags: string[];
  version: number;
  updated_at: Date;
  source: string | null;
}

function renderMemories(heading: string, rows: MemoryExportRow[]): string {
  const lines = [`# ${heading}`, '', `<!-- Generated by NIO-Book at ${new Date().toISOString()}. Do not edit; changes are overwritten. -->`, ''];
  for (const m of rows) {
    lines.push(`## ${m.title}`, '');
    lines.push(m.content.trim(), '');
    const meta = [`id: ${m.id}`, `v${m.version}`, `updated: ${new Date(m.updated_at).toISOString()}`];
    if (m.source) meta.push(`source: @${m.source}`);
    if (m.tags.length) meta.push(`tags: ${m.tags.join(', ')}`);
    lines.push(`_${meta.join(' · ')}_`, '');
  }
  return lines.join('\n');
}

const MEMORY_QUERY = `SELECT m.id, m.title, m.content, m.tags, m.version, m.updated_at, p.handle AS source
  FROM memories m LEFT JOIN participants p ON p.id = m.source_participant_id
  WHERE m.status = 'active' AND %WHERE% ORDER BY m.title`;

/**
 * Writes the shared-context tree:
 *   memory/global.md, memory/decisions.md, memory/preferences.md, memory/projects/{slug}.md,
 *   sessions/{id}/metadata.json, messages.jsonl, state.json.
 * Agent-private memories are not exported.
 */
export async function exportAll(ctx: Ctx): Promise<{ projects: number; sessions: number }> {
  const root = ctx.config.dataDir;
  const global = await ctx.db.query<MemoryExportRow>(MEMORY_QUERY.replace('%WHERE%', `m.scope = 'global'`));
  await writeAtomic(path.join(root, 'memory', 'global.md'), renderMemories('Global memory', global.rows));
  for (const [tag, file, heading] of [
    ['decision', 'decisions.md', 'Decisions'],
    ['preference', 'preferences.md', 'Preferences'],
  ] as const) {
    const tagged = await ctx.db.query<MemoryExportRow>(
      MEMORY_QUERY.replace('%WHERE%', `m.scope IN ('global', 'project') AND $1 = ANY(m.tags)`),
      [tag],
    );
    await writeAtomic(path.join(root, 'memory', file), renderMemories(heading, tagged.rows));
  }

  const projects = await ctx.db.query('SELECT id, slug, name FROM projects WHERE archived_at IS NULL');
  for (const p of projects.rows) {
    const rows = await ctx.db.query<MemoryExportRow>(MEMORY_QUERY.replace('%WHERE%', `m.scope = 'project' AND m.project_id = $1`), [p.id]);
    // Slugs are constrained to [a-z0-9-] by the schema, so they are safe path segments.
    await writeAtomic(path.join(root, 'memory', 'projects', `${p.slug}.md`), renderMemories(`${p.name} — project memory`, rows.rows));
  }

  const sessions = await ctx.db.query(
    `SELECT s.*, s.last_seq::int AS last_seq, p.slug AS project_slug FROM sessions s JOIN projects p ON p.id = s.project_id
      WHERE s.kind <> 'dm'`,
  );
  for (const s of sessions.rows) {
    const dir = sessionDir(root, s.id);
    const participants = await ctx.db.query(
      `SELECT p.handle, p.kind, sp.joined_at FROM session_participants sp JOIN participants p ON p.id = sp.participant_id
        WHERE sp.session_id = $1 AND sp.left_at IS NULL`,
      [s.id],
    );
    await writeAtomic(
      path.join(dir, 'metadata.json'),
      JSON.stringify(
        { id: s.id, project: s.project_slug, kind: s.kind, title: s.title, status: s.status, created_at: s.created_at, updated_at: s.updated_at, participants: participants.rows },
        null,
        2,
      ),
    );
    const messages = await ctx.db.query(
      `SELECT m.seq::int AS seq, m.id, p.handle AS author, p.kind AS author_kind, m.kind, m.content, m.usage, m.created_at
         FROM messages m JOIN participants p ON p.id = m.author_id WHERE m.session_id = $1 ORDER BY m.seq`,
      [s.id],
    );
    await writeAtomic(path.join(dir, 'messages.jsonl'), messages.rows.map((m) => JSON.stringify(m)).join('\n') + (messages.rows.length ? '\n' : ''));
    const checkpoint = await ctx.db.query(
      `SELECT label, summary, state, at_seq::int AS at_seq, created_at FROM checkpoints WHERE session_id = $1 ORDER BY created_at DESC LIMIT 1`,
      [s.id],
    );
    await writeAtomic(
      path.join(dir, 'state.json'),
      JSON.stringify({ status: s.status, summary: s.summary, last_seq: s.last_seq, latest_checkpoint: checkpoint.rows[0] ?? null }, null, 2),
    );
  }
  return { projects: projects.rows.length, sessions: sessions.rows.length };
}
